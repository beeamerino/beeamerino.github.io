#!/usr/bin/env python3
"""Build the photo gallery from data/gallery.csv (stdlib only; runs before every render).

- Rows with publish = si/sí/yes are shown, in CSV order.
- The JPG is copied from fotos_procesadas/ (never published) to assets/gallery/ (published).
- A row with `answer = x,y,r` (percent of width/height; r = radius as % of width) becomes a
  "¿Lo encuentras?" game: the photo with a button that reveals a circle around the plant.
"""
import csv, html, re, shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV = ROOT / "data" / "gallery.csv"
DEST = ROOT / "assets" / "gallery"
TXT = {
    "es": {"show": "Ver respuesta", "hide": "Ocultar respuesta", "game": "¿Lo encuentras?", "prefix": ""},
    "en": {"show": "Show answer", "hide": "Hide answer", "game": "Can you spot it?", "prefix": "../"},
}


LINK = re.compile(r"\[([^\]]+)\]\((https?://[^)\s]+)\)")


def md_inline(s):
    """*italic* -> <em>, [text](url) -> link; escape the rest (captions go inside raw HTML)."""
    s = html.escape(s, quote=False)
    s = LINK.sub(lambda m: f'<a href="{m.group(2)}" target="_blank" rel="noopener">{m.group(1)}</a>', s)
    return re.sub(r"\*([^*]+)\*", r"<em>\1</em>", s)


def plain(s):
    """Caption text for the lightbox: links reduced to their text, no asterisks."""
    return LINK.sub(r"\1", s).replace("*", "")


def read_csv(path):
    """Tolerant reader: spreadsheets (Numbers/Excel) often save CSVs in Mac Roman or
    Windows-1252, or with ';' separators. Valid UTF-8 is kept; any other byte is decoded
    as Mac Roman. Dates like 28-09-23 or 28/09/2023 are normalized to 2023-09-28."""
    import codecs, io
    def fallback(err):
        bad = err.object[err.start:err.end]
        return bad.decode("mac_roman"), err.end
    codecs.register_error("plantlab_macroman", fallback)
    text = path.read_bytes().decode("utf-8-sig", errors="plantlab_macroman")
    delim = ";" if text.split("\n", 1)[0].count(";") > text.split("\n", 1)[0].count(",") else ","
    rows = list(csv.DictReader(io.StringIO(text), delimiter=delim))
    for r in rows:
        d = (r.get("date") or "").strip()
        m = re.fullmatch(r"(\d{1,2})[-/](\d{1,2})[-/](\d{2}|\d{4})", d)
        if m:
            y = m.group(3) if len(m.group(3)) == 4 else "20" + m.group(3)
            r["date"] = f"{y}-{int(m.group(2)):02d}-{int(m.group(1)):02d}"
    return rows


def main():
    if not CSV.exists():
        return
    rows = [r for r in read_csv(CSV)
            if (r.get("publish") or "").strip().lower() in ("si", "sí", "yes", "y", "x")]
    DEST.mkdir(parents=True, exist_ok=True)
    for r in rows:
        src = ROOT / r["file"]
        dst = DEST / Path(r["file"]).name
        if src.exists() and (not dst.exists() or src.stat().st_mtime > dst.stat().st_mtime):
            shutil.copy2(src, dst)
    # prune: photos no longer selected are removed from the published folder
    keep = {Path(r["file"]).name for r in rows}
    for old in DEST.glob("*.jpg"):
        if old.name not in keep:
            try:
                old.unlink()
            except OSError:
                print(f"build_gallery: could not remove {old.name}; delete it by hand")
    for lang, t in TXT.items():
        out = ['<!-- AUTO-GENERATED by scripts/build_gallery.py from data/gallery.csv. Do not edit. -->', '',
               '```{=html}', '<div class="gallery-grid">']
        for i, r in enumerate(rows):
            name = Path(r["file"]).name
            src = f'{t["prefix"]}assets/gallery/{name}'
            def f(col):  # English page uses caption_en / alt_en / location_en / comment_en when filled
                return (r.get(f"{col}_en") or "").strip() if lang == "en" and (r.get(f"{col}_en") or "").strip() else (r.get(col) or "")
            cap = md_inline(f("caption"))
            meta = f("location").strip()   # dates stay in the CSV only; not shown on the site
            comment = md_inline(f("comment").strip())
            alt = html.escape(f("alt") or f("caption"))
            figcap = f'<figcaption>{cap}' + (f'<span class="g-meta">{html.escape(meta)}</span>' if meta else "") \
                     + (f'<span class="g-comment">{comment}</span>' if comment else "") + '</figcaption>'
            ans = r.get("answer", "").strip()
            if ans:
                x, y, rad = [float(v) for v in ans.split(",")]
                out += [f'<figure class="g-item g-game">',
                        f'<div class="g-frame"><img src="{src}" alt="{alt}" loading="lazy">',
                        f'<span class="g-answer" hidden style="left:{x}%;top:{y}%;width:{2*rad}%;"></span></div>',
                        f'<button type="button" class="btn btn-sm btn-outline-secondary g-reveal" '
                        f'data-show="{t["show"]}" data-hide="{t["hide"]}">{t["show"]}</button>',
                        figcap, '</figure>']
            else:
                out += [f'<figure class="g-item"><a href="{src}" class="lightbox" data-gallery="galeria" '
                        f'data-description="{html.escape(plain(f("caption")))}">'
                        f'<img src="{src}" alt="{alt}" loading="lazy"></a>', figcap, '</figure>']
        out += ['</div>', '<script>',
                'document.querySelectorAll(".g-reveal").forEach(function (b) {',
                '  b.addEventListener("click", function () {',
                '    var a = b.parentElement.querySelector(".g-answer"); a.hidden = !a.hidden;',
                '    b.textContent = a.hidden ? b.dataset.show : b.dataset.hide; });',
                '});', '</script>', '```', '']
        (ROOT / f"_gallery_{lang}.md").write_text("\n".join(out), encoding="utf-8")
    print(f"build_gallery: {len(rows)} photos")


if __name__ == "__main__":
    main()
